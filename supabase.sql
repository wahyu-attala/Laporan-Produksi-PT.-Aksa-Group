create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  client text not null,
  wo text not null unique,
  item text not null,
  type text not null,
  qty integer not null check (qty > 0),
  position text not null default '',
  stages jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.editors (
  email text primary key,
  name text,
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;
alter table public.editors enable row level security;

drop policy if exists "Public dapat melihat order" on public.orders;
create policy "Public dapat melihat order" on public.orders for select using (true);

drop policy if exists "Editor dapat menambah order" on public.orders;
create policy "Editor dapat menambah order" on public.orders for insert to authenticated
with check (exists (select 1 from public.editors where lower(editors.email) = lower(auth.jwt()->>'email')));

drop policy if exists "Editor dapat mengubah order" on public.orders;
create policy "Editor dapat mengubah order" on public.orders for update to authenticated
using (exists (select 1 from public.editors where lower(editors.email) = lower(auth.jwt()->>'email')))
with check (exists (select 1 from public.editors where lower(editors.email) = lower(auth.jwt()->>'email')));

drop policy if exists "Editor dapat menghapus order" on public.orders;
create policy "Editor dapat menghapus order" on public.orders for delete to authenticated
using (exists (select 1 from public.editors where lower(editors.email) = lower(auth.jwt()->>'email')));

drop policy if exists "Editor dapat melihat daftar editor" on public.editors;
create policy "Editor dapat melihat daftar editor" on public.editors for select to authenticated
using (exists (select 1 from public.editors e where lower(e.email) = lower(auth.jwt()->>'email')));

